import 'package:flutter/material.dart';
import 'package:path_drawing/path_drawing.dart';

class FacePainter extends CustomPainter {
  FacePainter({required this.color, required this.strokeWidth});

  static const Size _originalSize = Size(280, 280);
  static const Offset _eyeCenter = Offset(50.75, 138.25);
  static const double _eyeRadius = 5.25;

  final Color color;
  final double strokeWidth;

  @override
  void paint(Canvas canvas, Size size) {
    final scaleX = size.width / _originalSize.width;
    final scaleY = size.height / _originalSize.height;

    final matrix = Matrix4.diagonal3Values(scaleX, scaleY, 1);
    final path = parseSvgPathData(_pathData).transform(matrix.storage);

    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeCap = StrokeCap.round
      ..strokeWidth = strokeWidth;

    canvas.drawPath(path, paint);

    canvas.save();
    canvas.scale(scaleX, scaleY);
    canvas.drawCircle(
      _eyeCenter,
      _eyeRadius,
      Paint()
        ..color = color
        ..style = PaintingStyle.fill,
    );
    canvas.restore();
  }

  @override
  bool shouldRepaint(covariant FacePainter oldDelegate) =>
      oldDelegate.color != color;
}

